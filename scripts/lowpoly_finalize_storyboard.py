"""Tighten pacing, build the storyboard and bake lip sync for a Lowpoly style bundle video.

Usage:
    python scripts/lowpoly_finalize_storyboard.py <project>

Run after ``python -m src.cli voiceover <project>``. Trims TTS silence, rebuilds the storyboard with the lowpoly
pacing (0.4 s between scenes, 10-frame dissolves), then writes ``scenes/lipsync.ts``: mouth openness per frame
(30 fps) measured from each trimmed ``voiceover/<scene_id>.mp3`` and the caption text of every scene. Needs ffmpeg.
"""

from __future__ import annotations

import argparse
import array
import json
import subprocess
import sys
from pathlib import Path

from _storyboard_pacing import REPO_ROOT, finalize

BUFFER_SECONDS = 0.4
TRANSITION = {"style": "fade", "duration_frames": 10}
FPS = 30
RATE = 16000


def mouth_curve(mp3: Path) -> list[float]:
    """Loudness per 1/30 s window, normalised to 0..1 and lightly smoothed: how far the mouth opens."""
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(mp3), "-ac", "1", "-ar", str(RATE), "-f", "s16le", "-"],
        capture_output=True, check=True,
    ).stdout
    samples = array.array("h")
    samples.frombytes(raw[: len(raw) // 2 * 2])
    step = RATE // FPS
    rms = []
    for i in range(0, len(samples) - step + 1, step):
        chunk = samples[i:i + step]
        rms.append((sum(s * s for s in chunk) / step) ** 0.5)
    if not rms:
        return []
    ordered = sorted(rms)
    ref = max(ordered[int(len(ordered) * 0.92)], 1.0)
    floor = ref * 0.08
    raw_open = [0.0 if r < floor else min(1.0, (r / ref) ** 0.8) for r in rms]
    smooth = []
    for i, x in enumerate(raw_open):
        prev = raw_open[i - 1] if i else x
        smooth.append(round(0.6 * x + 0.4 * prev, 2))
    return smooth


def write_lipsync_ts(project_dir: Path, lipsync: dict[str, list[float]]) -> Path:
    narr = json.loads((project_dir / "narration" / "narrations.json").read_text(encoding="utf-8"))
    captions = {s["scene_id"]: s.get("narration", "") for s in narr["scenes"]}
    out = project_dir / "scenes" / "lipsync.ts"
    out.write_text(
        "/** Generated by scripts/lowpoly_finalize_storyboard.py (mouth openness per frame from the voiceover, captions from the narration). */\n"
        f"export const LIPSYNC: Record<string, number[] | undefined> = {json.dumps(lipsync)};\n"
        f"export const CAPTIONS: Record<string, string | undefined> = {json.dumps(captions, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
    )
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("project")
    parser.add_argument("--projects-dir", default=str(REPO_ROOT / "projects"))
    args = parser.parse_args(argv)
    code = finalize(args.project, args.projects_dir, BUFFER_SECONDS, TRANSITION)
    if code:
        return code
    project_dir = Path(args.projects_dir) / args.project
    lipsync = {mp3.stem: mouth_curve(mp3) for mp3 in sorted((project_dir / "voiceover").glob("*.mp3"))}
    path = write_lipsync_ts(project_dir, lipsync)
    print(f"Lip sync for {len(lipsync)} scenes written to {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
