"""Build the scenes, registry, dialogue captions and narration of a MovieBook video from its plan.

Usage:
    python scripts/moviebook_build_scenes.py <project> [--projects-dir DIR]

``projects/<project>/moviebook/plan.json`` is the single source of truth (cast, voice anchors, shots). This writes
``scenes/<id>.tsx`` (one ``ClipShot`` per shot), ``scenes/index.ts``, ``scenes/dialogue.ts`` and
``narration/narrations.json`` (the spoken line of each shot, which the review and the Whisper check read). Clip frame
counts come from ``moviebook/clips.json`` (written by ``moviebook_finalize_storyboard.py`` after it measures the
clips, in 30 fps composition frames); until then the plan's ``frames`` at the clip rate ``fps`` is converted. Never hand-edit the generated files: edit the plan and re-run.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from src.cli.main import _title_to_scene_key  # noqa: E402

COMP_FPS = 30  # every bundle renders through the 30 fps ScenePlayer composition; clips (plan.fps, 24) are retimed to it

GENERATED = "// Generated by scripts/moviebook_build_scenes.py from moviebook/plan.json. Do not edit; edit the plan and re-run.\n"


def shot_id(shot: dict) -> str:
    return _title_to_scene_key(shot["title"])


def pascal(sid: str) -> str:
    return "".join(p.capitalize() for p in sid.split("_")) + "Scene"


def validate(plan: dict) -> list[str]:
    errors = []
    cast = plan.get("cast", {})
    seen: set[str] = set()
    if not plan.get("shots"):
        errors.append("plan has no shots")
    for i, s in enumerate(plan.get("shots", []), 1):
        if not s.get("title"):
            errors.append(f"shot {i} has no title")
            continue
        sid = shot_id(s)
        if sid in seen:
            errors.append(f"shot titles must be unique: {s['title']!r} gives the duplicate id {sid!r}")
        seen.add(sid)
        if s.get("speaker") and s["speaker"] not in cast:
            errors.append(f"{sid}: speaker {s['speaker']!r} is not in cast")
        for c in s.get("cast", []):
            if c not in cast:
                errors.append(f"{sid}: cast member {c!r} is not in cast")
        if s.get("speaker") and not s.get("line"):
            errors.append(f"{sid}: has a speaker but no line")
    return errors


def scene_tsx(sid: str, clip_frames: int) -> str:
    comp = pascal(sid)
    return (
        GENERATED
        + 'import React from "react";\n'
        + 'import { ClipShot } from "@remotion-components/moviebook/kit";\n'
        + 'import { DIALOGUE } from "./dialogue";\n\n'
        + f"export const {comp}: React.FC<{{ startFrame?: number }}> = () => (\n"
        + f'  <ClipShot clip="moviebook/clips/{sid}.mp4" clipFrames={{{clip_frames}}} dialogue={{DIALOGUE["{sid}"]}} />\n'
        + ");\n"
        + f"export default {comp};\n"
    )


def index_ts(sids: list[str]) -> str:
    imports = "\n".join(f'import {pascal(s)} from "./{s}";' for s in sids)
    entries = "\n".join(f"  {s}: {pascal(s)}," for s in sids)
    return (
        "/**\n * MovieBook style bundle scene registry (generated by scripts/moviebook_build_scenes.py). Keys equal the slug of\n"
        ' * each scene title; component names end in "Scene" because the storyboard CLI parses this file with regexes.\n */\n\n'
        'import React from "react";\n\n'
        + imports
        + "\n\nexport type SceneComponent = React.FC<{ startFrame?: number }>;\n\n"
        + "const SCENE_REGISTRY: Record<string, SceneComponent> = {\n"
        + entries
        + "\n};\n\n// Standard export name for the build system (required by remotion/src/scenes/index.ts)\n"
        + "export const PROJECT_SCENES = SCENE_REGISTRY;\n\n"
        + "export function getScene(type: string): SceneComponent | undefined {\n  return SCENE_REGISTRY[type];\n}\n\n"
        + "export function getAvailableSceneTypes(): string[] {\n  return Object.keys(SCENE_REGISTRY);\n}\n"
    )


def dialogue_ts(plan: dict) -> str:
    cast = plan.get("cast", {})
    table = {}
    for s in plan["shots"]:
        if s.get("speaker"):
            c = cast[s["speaker"]]
            tone = c.get("gender") if c.get("gender") in ("female", "male") else "neutral"
            table[shot_id(s)] = {"speaker": c["name"], "text": s["line"], "tone": tone}
    type_ = '{ speaker: string; text: string; tone?: "female" | "male" | "neutral" } | undefined'
    return GENERATED + f"export const DIALOGUE: Record<string, {type_}> = " + json.dumps(table, indent=2, ensure_ascii=False) + ";\n"


def planned_frames(plan: dict, shot: dict) -> int:
    """Clip length in composition frames (30 fps) from the plan's clip frames and clip rate."""
    return round(shot.get("frames", plan.get("frames", 90)) / plan.get("fps", 24) * COMP_FPS)


def narrations(plan: dict, frames_by_id: dict[str, int]) -> dict:
    out = []
    for s in plan["shots"]:
        sid = shot_id(s)
        secs = frames_by_id[sid] / COMP_FPS
        out.append({"scene_id": sid, "title": s["title"], "duration_seconds": round(max(secs, 1.0), 2), "narration": s.get("line", "")})
    return {"scenes": out}


def build(project_dir: Path) -> int:
    plan_path = project_dir / "moviebook" / "plan.json"
    if not plan_path.exists():
        print(f"{plan_path} not found (run scripts/moviebook_new_video.py first)", file=sys.stderr)
        return 1
    plan = json.loads(plan_path.read_text(encoding="utf-8"))
    errors = validate(plan)
    if errors:
        print("Plan errors:\n  " + "\n  ".join(errors), file=sys.stderr)
        return 1
    clips_json = project_dir / "moviebook" / "clips.json"
    measured = json.loads(clips_json.read_text(encoding="utf-8")) if clips_json.exists() else {}
    sids = [shot_id(s) for s in plan["shots"]]
    frames_by_id = {shot_id(s): int(measured.get(shot_id(s), {}).get("frames", planned_frames(plan, s))) for s in plan["shots"]}
    scenes = project_dir / "scenes"
    scenes.mkdir(parents=True, exist_ok=True)
    for old in scenes.glob("*.tsx"):
        if old.read_text(encoding="utf-8").startswith(GENERATED):
            old.unlink()  # a renamed or dropped shot must not leave a stale scene behind
    for sid in sids:
        (scenes / f"{sid}.tsx").write_text(scene_tsx(sid, frames_by_id[sid]), encoding="utf-8")
    (scenes / "index.ts").write_text(index_ts(sids), encoding="utf-8")
    (scenes / "dialogue.ts").write_text(dialogue_ts(plan), encoding="utf-8")
    narration_path = project_dir / "narration" / "narrations.json"
    narration_path.parent.mkdir(parents=True, exist_ok=True)
    narration_path.write_text(json.dumps(narrations(plan, frames_by_id), indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Built {len(sids)} scenes, index.ts, dialogue.ts and narration for {project_dir.name}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("project")
    parser.add_argument("--projects-dir", default=str(REPO_ROOT / "projects"))
    args = parser.parse_args(argv)
    return build(Path(args.projects_dir) / args.project)


if __name__ == "__main__":
    sys.exit(main())
