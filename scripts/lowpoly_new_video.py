"""Scaffold a Lowpoly style bundle video (landscape 1280x720): scenes, starter narration, config.

Usage:
    python scripts/lowpoly_new_video.py <project> [--force]

Copies ``templates/lowpoly_video/scenes/`` to ``projects/<project>/scenes/``, writes a starter
``narration/narrations.json`` (a neutral six-beat story arc: hello, problem, idea, steps, twist, finale), writes a
captions-only ``scenes/lipsync.ts`` and sets the project config for the lowpoly style bundle (1280x720, 30 fps,
edge TTS). Replace the story, then run: review_video, radio_cut, voiceover, ``scripts/lowpoly_finalize_storyboard.py``,
render. Mouth movement and captions are generated by the finalize step from the voiceover.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

from _lipsync import write_lipsync_ts

REPO_ROOT = Path(__file__).resolve().parent.parent
TEMPLATE_DIR = REPO_ROOT / "templates" / "lowpoly_video" / "scenes"

# scene_id (registry key), title, starter narration. The registry key must equal the slug of the title.
SAMPLE_SCENES = [
    ("hello", "Hello", "Hi there. Today I will show you something that looks hard, but is not."),
    ("problem", "Problem", "Most people put it off, because they are not sure where to start."),
    ("idea", "Idea", "But once you see how the pieces fit together, the rest is easy."),
    ("steps", "Steps", "First, look. Second, prepare. Third, do it, slowly."),
    ("twist", "Twist", "And the part everyone worries about, turns out to be the simplest."),
    ("finale", "Finale", "That is all it takes. Now you can do it yourself."),
]
WORDS_PER_SECOND = 2.3


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("project", help="Project id (folder under projects/)")
    parser.add_argument("--projects-dir", default=str(REPO_ROOT / "projects"))
    parser.add_argument("--force", action="store_true", help="Overwrite existing scenes/narration")
    args = parser.parse_args(argv)

    project_dir = Path(args.projects_dir) / args.project
    config_path = project_dir / "config.json"
    if not config_path.exists():
        print(f"Project not found: {project_dir} (run: python -m src.cli create {args.project})", file=sys.stderr)
        return 1
    scenes_dir = project_dir / "scenes"
    narration_path = project_dir / "narration" / "narrations.json"
    if not args.force and (any(scenes_dir.glob("*.tsx")) or narration_path.exists()):
        print("Scenes or narration already exist; use --force to overwrite", file=sys.stderr)
        return 1

    scenes_dir.mkdir(parents=True, exist_ok=True)
    for src in TEMPLATE_DIR.glob("*"):
        shutil.copy2(src, scenes_dir / src.name)

    narration_path.parent.mkdir(parents=True, exist_ok=True)
    narration_path.write_text(json.dumps({"scenes": [
        {"scene_id": sid, "title": title, "duration_seconds": round(max(3.0, len(text.split()) / WORDS_PER_SECOND + 1.0), 1), "narration": text}
        for sid, title, text in SAMPLE_SCENES
    ]}, indent=2), encoding="utf-8")
    write_lipsync_ts(project_dir, {})

    config = json.loads(config_path.read_text(encoding="utf-8"))
    config["style_bundle"] = "lowpoly"
    config.setdefault("video", {}).update({"resolution": {"width": 1280, "height": 720}, "fps": 30, "target_duration_seconds": 36})
    config.setdefault("tts", {})["provider"] = "edge"
    config["style"] = {"background_color": "#a9ad93", "primary_color": "#b4531f", "secondary_color": "#6f8a6b", "font_family": "Fraunces"}
    config_path.write_text(json.dumps(config, indent=2), encoding="utf-8")

    print(f"Scenes copied to {scenes_dir}")
    print('Project config set to "style_bundle": "lowpoly", 1280x720')
    print("Next: edit narration and scenes, review_video, radio_cut, voiceover, lowpoly_finalize_storyboard, render")
    return 0


if __name__ == "__main__":
    sys.exit(main())
